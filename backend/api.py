@app.post("/api/sources")
def add_source(payload: SourceIn):
    allowed = {"sqlite", "mongodb", "neo4j"}
    if payload.kind not in allowed:
        raise HTTPException(400, f"Type non supporté. Types autorisés: {sorted(allowed)}")
    return registry.add_source(payload.name, payload.kind, payload.connection)

@app.post("/api/sources/sqlite-upload")
async def upload_sqlite_source(name: str = Form(...), file: UploadFile = File(...)):
    """Store a user-selected SQLite database locally and register it read-only."""
    suffix = Path(file.filename or "").suffix.lower()
    if suffix not in {".sqlite", ".sqlite3", ".db"}:
        raise HTTPException(400, "Choisis un fichier SQLite (.sqlite, .sqlite3 ou .db).")
    clean_name = name.strip()
    if not clean_name or len(clean_name) > 100:
        raise HTTPException(422, "Le nom de la source doit contenir de 1 à 100 caractères.")
    content = await file.read()
    if len(content) > MAX_UPLOAD_MB * 1024 * 1024:
        raise HTTPException(413, f"Fichier trop volumineux (limite {MAX_UPLOAD_MB} Mo)")
    if not content.startswith(b"SQLite format 3\x00"):
        raise HTTPException(400, "Le fichier choisi n'est pas une base SQLite valide.")

    storage_dir = UPLOAD_DIR / "sqlite_sources"
    storage_dir.mkdir(parents=True, exist_ok=True)
    destination = storage_dir / f"{uuid4().hex}{suffix}"
    destination.write_bytes(content)
    try:
        # Check that SQLite can open the uploaded database before registering it.
        with sqlite3.connect(destination.resolve().as_uri() + "?mode=ro", uri=True) as db:
            check = db.execute("PRAGMA quick_check").fetchone()
            if not check or check[0] != "ok":
                raise sqlite3.DatabaseError("SQLite quick_check failed")
        return registry.add_source(clean_name, "sqlite", str(destination))
    except Exception as exc:
        destination.unlink(missing_ok=True)
        raise HTTPException(400, "Impossible d'ouvrir cette base SQLite.") from exc

