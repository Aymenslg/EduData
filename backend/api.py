@app.post("/api/files/upload")
async def upload_file(file: UploadFile = File(...)):
    suffix = Path(file.filename or "").suffix.lower()
    if suffix not in {".pdf", ".csv", ".xlsx", ".xls", ".json"}:
        raise HTTPException(400, "Formats acceptés : PDF, CSV, XLSX, XLS, JSON")
    content = await file.read()
    if len(content) > MAX_UPLOAD_MB * 1024 * 1024:
        raise HTTPException(413, f"Fichier trop volumineux (limite {MAX_UPLOAD_MB} Mo)")
    original_name = file.filename or f"fichier{suffix}"
    safe_name = re.sub(r"[^\w .-]+", "_", Path(original_name).name, flags=re.UNICODE).strip(" .")[:100]
    if not safe_name:
        safe_name = f"fichier{suffix}"
    if Path(safe_name).suffix.lower() != suffix:
        safe_name = f"{Path(safe_name).stem}{suffix}"
    # The storage key is generated by the server; the client filename is metadata only.
    stored_name = f"{uuid4().hex}{suffix}"
    destination = UPLOAD_DIR / stored_name
    destination.write_bytes(content)
    try:
        info = inspect_file(destination)
    except Exception as exc:
        destination.unlink(missing_ok=True)
        raise HTTPException(400, f"Impossible de lire ce fichier : {exc}")
    destination.with_name(destination.name + ".meta.json").write_text(
        json.dumps({"filename": safe_name}, ensure_ascii=False), encoding="utf-8")
    return {"id": stored_name, "filename": safe_name, **info}

@app.get("/api/files")
def list_files():
    result = []
    for path in UPLOAD_DIR.iterdir():
        if path.is_file() and re.fullmatch(r"[0-9a-f]{32}(?:\.(?:pdf|csv|xlsx|xls|json)|_[\w .-]{1,100})", path.name):
            metadata_path = path.with_name(path.name + ".meta.json")
            if metadata_path.is_file():
                try:
                    filename = json.loads(metadata_path.read_text(encoding="utf-8")).get("filename", path.name)
                except Exception:
                    filename = "Fichier " + path.suffix.lstrip(".")
            else:
                filename = path.name[33:] if "_" in path.name[:33] else "Fichier " + path.suffix.lstrip(".")
            result.append({"id": path.name, "filename": filename,
                           "size_bytes": path.stat().st_size})
    return result

